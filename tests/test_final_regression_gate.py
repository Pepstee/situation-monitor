def _stub_env() -> dict[str, str]:
    """Force stub LLM and fixture RSS so no live network calls are needed."""
    return {
        **os.environ,
        "SM_LLM_BACKEND": "stub",
        "SM_SOURCES": "tests/fixtures/rss_sample.xml",
    }


