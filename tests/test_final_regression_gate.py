class TestVerdictBriefConfirmsAllThree:
    """Criterion 3: verdict_brief.txt must confirm DUAL_LENS: Y, SPIN_PCT: Y, MARKET: Y."""

    def test_verdict_file_exists(self) -> None:
        assert VERDICT_FILE.exists(), (
            f"verdict_brief.txt not found at {VERDICT_FILE}.\n"
            "Run evidence.py to generate it before executing this gate."
        )

    def test_verdict_file_is_non_empty(self) -> None:
        assert VERDICT_FILE.read_text().strip(), (
            "verdict_brief.txt must not be empty"
        )

    def test_verdict_has_at_least_three_lines(self, verdict_lines: list[str]) -> None:
        assert len(verdict_lines) >= 3, (
            f"verdict_brief.txt must contain at least 3 non-empty lines; "
            f"got {len(verdict_lines)}: {verdict_lines!r}"
        )

    def test_dual_lens_y_on_line_one(self, verdict_lines: list[str]) -> None:
        """Line 1 must be exactly 'DUAL_LENS: Y' — confirms dual-lens pipeline captured both sides."""
        assert len(verdict_lines) >= 1, "verdict_brief.txt has no content"
        assert verdict_lines[0] == "DUAL_LENS: Y", (
            f"verdict_brief.txt line 1 must be 'DUAL_LENS: Y'; "
            f"got {verdict_lines[0]!r}.\n"
            "DUAL_LENS is 'Y' only when the pipeline has articles in BOTH left and right buckets."
        )

    def test_spin_pct_y_on_line_two(self, verdict_lines: list[str]) -> None:
        """Line 2 must be exactly 'SPIN_PCT: Y' — confirms spin estimation ran on at least one article."""
        assert len(verdict_lines) >= 2, (
            "verdict_brief.txt must have at least 2 non-empty lines"
        )
        assert verdict_lines[1] == "SPIN_PCT: Y", (
            f"verdict_brief.txt line 2 must be 'SPIN_PCT: Y'; "
            f"got {verdict_lines[1]!r}.\n"
            "SPIN_PCT is 'Y' only when spin estimation produced at least one spin_pct value."
        )

    def test_market_y_on_line_three(self, verdict_lines: list[str]) -> None:
        """Line 3 must be exactly 'MARKET: Y' — confirms fetch_practical_movers returned data."""
        assert len(verdict_lines) >= 3, (
            "verdict_brief.txt must have at least 3 non-empty lines"
        )
        assert verdict_lines[2] == "MARKET: Y", (
            f"verdict_brief.txt line 3 must be 'MARKET: Y'; "
            f"got {verdict_lines[2]!r}.\n"
            "MARKET is 'Y' only when fetch_practical_movers() returns at least one mover."
        )

    def test_all_three_criteria_composite(self, verdict_lines: list[str]) -> None:
        """Composite check: all three lines correct in a single assertion for quick triage."""
        assert len(verdict_lines) >= 3, (
            f"verdict_brief.txt must have at least 3 lines; got {len(verdict_lines)}"
        )
        expected = ["DUAL_LENS: Y", "SPIN_PCT: Y", "MARKET: Y"]
        for i, exp in enumerate(expected):
            got = verdict_lines[i]
            assert got == exp, (
                f"verdict_brief.txt line {i + 1}: expected {exp!r}, got {got!r}"
            )

    def test_values_are_y_not_n(self, verdict_lines: list[str]) -> None:
        """All three lines must carry the 'Y' (pass) indicator, not 'N' (fail)."""
        for i, line in enumerate(verdict_lines[:3]):
            parts = line.split(":", 1)
            assert len(parts) == 2, (
                f"Line {i + 1} is malformed (no ':'): {line!r}"
            )
            value = parts[1].strip()
            assert value == "Y", (
                f"verdict_brief.txt line {i + 1} value must be 'Y'; got {value!r}.\n"
                f"Full line: {line!r}"
            )

    def test_dual_lens_key_is_correct(self, verdict_lines: list[str]) -> None:
        """The key on line 1 must be exactly 'DUAL_LENS' (not 'DUAL-LENS' or a typo)."""
        assert len(verdict_lines) >= 1
        key = verdict_lines[0].split(":", 1)[0]
        assert key == "DUAL_LENS", (
            f"Line 1 key must be 'DUAL_LENS'; got {key!r}"
        )

    def test_spin_pct_key_is_correct(self, verdict_lines: list[str]) -> None:
        """The key on line 2 must be exactly 'SPIN_PCT' (not 'SPIN_PERCENT' or a typo)."""
        assert len(verdict_lines) >= 2
        key = verdict_lines[1].split(":", 1)[0]
        assert key == "SPIN_PCT", (
            f"Line 2 key must be 'SPIN_PCT'; got {key!r}"
        )

    def test_market_key_is_correct(self, verdict_lines: list[str]) -> None:
        """The key on line 3 must be exactly 'MARKET'."""
        assert len(verdict_lines) >= 3
        key = verdict_lines[2].split(":", 1)[0]
        assert key == "MARKET", (
            f"Line 3 key must be 'MARKET'; got {key!r}"
        )

    def test_no_n_values_anywhere_in_first_three_lines(self, verdict_lines: list[str]) -> None:
        """None of the three values must be 'N' — that would indicate a failing criterion."""
        for i, line in enumerate(verdict_lines[:3]):
            parts = line.split(":", 1)
            if len(parts) == 2:
                value = parts[1].strip()
                assert value != "N", (
                    f"verdict_brief.txt line {i + 1} has a failing value 'N': {line!r}.\n"
                    "All three criteria must be 'Y' (pass)."
                )

    def test_file_ends_with_newline(self) -> None:
        """verdict_brief.txt must end with a newline — standard POSIX text file format."""
        text = VERDICT_FILE.read_text()
        assert text.endswith("\n"), (
            "verdict_brief.txt must end with a newline character"
        )
