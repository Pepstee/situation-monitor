class TestAcceptanceSubprocessReturncodeAndLensText:
    """Criterion 2: acceptance script must exit 0 and emit dual-lens column text."""

    def test_returncode_is_zero(
        self, acceptance_result: subprocess.CompletedProcess
    ) -> None:
        """Primary gate: a non-zero returncode means at least one subcommand failed."""
        stdout = acceptance_result.stdout.decode(errors="replace")
        stderr = acceptance_result.stderr.decode(errors="replace")
        assert acceptance_result.returncode == 0, (
            f"Acceptance script exited {acceptance_result.returncode}; expected 0.\n"
            f"Both 'once' and 'digest-dry-run' subcommands must succeed.\n"
            f"stdout (first 2000):\n{stdout[:2000]}\n"
            f"stderr (first 500):\n{stderr[:500]}"
        )

    def test_left_lens_text_in_stdout(self, acceptance_stdout: str) -> None:
        """'#### LEFT' must appear in acceptance stdout — the left lens column heading."""
        assert "#### LEFT" in acceptance_stdout, (
            "Acceptance stdout must contain '#### LEFT' lens column heading.\n"
            "This is emitted by _print_dual_lens() in the 'once' subcommand.\n"
            f"Acceptance stdout (first 2000 chars):\n{acceptance_stdout[:2000]}"
        )

    def test_right_lens_text_in_stdout(self, acceptance_stdout: str) -> None:
        """'#### RIGHT' must appear in acceptance stdout — the right lens column heading."""
        assert "#### RIGHT" in acceptance_stdout, (
            "Acceptance stdout must contain '#### RIGHT' lens column heading.\n"
            "This is emitted by _print_dual_lens() in the 'once' subcommand.\n"
            f"Acceptance stdout (first 2000 chars):\n{acceptance_stdout[:2000]}"
        )

    def test_left_heading_is_exact_h4(self, acceptance_stdout: str) -> None:
        """'#### LEFT' must appear at the start of a line (proper H4, not inline prose)."""
        h4_left = [l for l in acceptance_stdout.splitlines() if l.startswith("#### LEFT")]
        assert h4_left, (
            "No line starting with '#### LEFT' found in acceptance stdout.\n"
            "The left column heading must be a proper H4 line."
        )

    def test_right_heading_is_exact_h4(self, acceptance_stdout: str) -> None:
        """'#### RIGHT' must appear at the start of a line (proper H4, not inline prose)."""
        h4_right = [l for l in acceptance_stdout.splitlines() if l.startswith("#### RIGHT")]
        assert h4_right, (
            "No line starting with '#### RIGHT' found in acceptance stdout.\n"
            "The right column heading must be a proper H4 line."
        )

    def test_both_lens_headings_inside_dual_lens_block(self, acceptance_stdout: str) -> None:
        """Both lens headings must appear AFTER the '## DUAL-LENS EVENTS' block header."""
        idx = acceptance_stdout.find("## DUAL-LENS EVENTS")
        assert idx >= 0, (
            "Acceptance stdout must contain '## DUAL-LENS EVENTS' block header"
        )
        block_text = acceptance_stdout[idx:]
        assert "#### LEFT" in block_text, (
            "'#### LEFT' must appear inside the DUAL-LENS EVENTS block"
        )
        assert "#### RIGHT" in block_text, (
            "'#### RIGHT' must appear inside the DUAL-LENS EVENTS block"
        )

    def test_left_column_contains_article_bullet(self, acceptance_stdout: str) -> None:
        """A '- ...' bullet must follow '#### LEFT' — the column must not be empty."""
        lines = acceptance_stdout.splitlines()
        in_left = False
        for line in lines:
            if line.startswith("#### LEFT"):
                in_left = True
                continue
            if in_left:
                if line.startswith("- "):
                    return  # found a bullet — test passes
                if line.startswith("#"):
                    break
        pytest.fail(
            "No '- ...' article bullet found under '#### LEFT' heading in acceptance stdout"
        )

    def test_right_column_contains_article_bullet(self, acceptance_stdout: str) -> None:
        """A '- ...' bullet must follow '#### RIGHT' — the column must not be empty."""
        lines = acceptance_stdout.splitlines()
        in_right = False
        for line in lines:
            if line.startswith("#### RIGHT"):
                in_right = True
                continue
            if in_right:
                if line.startswith("- "):
                    return  # found a bullet — test passes
                if line.startswith("#"):
                    break
        pytest.fail(
            "No '- ...' article bullet found under '#### RIGHT' heading in acceptance stdout"
        )

    def test_spin_pct_annotation_in_stdout(self, acceptance_stdout: str) -> None:
        """'spin_pct:' must appear in acceptance stdout — per-article spin annotation."""
        assert "spin_pct:" in acceptance_stdout, (
            "Acceptance stdout must contain 'spin_pct:' annotation in article bullets"
        )

    def test_spin_pct_value_is_numeric_float(self, acceptance_stdout: str) -> None:
        """spin_pct values must be parseable floats in the [0, 100] range."""
        matches = re.findall(r"spin_pct:\s*([\d.]+)%", acceptance_stdout)
        assert matches, (
            "No 'spin_pct: N.N%' pattern found in acceptance stdout"
        )
        for raw in matches:
            val = float(raw)
            assert 0.0 <= val <= 100.0, (
                f"spin_pct value {val}% is outside the valid 0–100 range"
            )

    def test_situation_monitor_heading_present(self, acceptance_stdout: str) -> None:
        """The output must begin with a 'Situation Monitor' heading."""
        assert "Situation Monitor" in acceptance_stdout, (
            "Acceptance stdout must contain the 'Situation Monitor' top-level heading"
        )

    def test_no_python_traceback(self, acceptance_stdout: str) -> None:
        """A Python traceback in stdout indicates an unhandled exception — not acceptable."""
        assert "Traceback (most recent call last)" not in acceptance_stdout, (
            "Acceptance stdout must not contain a Python traceback"
        )

    def test_top_stories_section_present(self, acceptance_stdout: str) -> None:
        """The digest-dry-run command (second half of acceptance) must emit *Top Stories*."""
        assert "*Top Stories*" in acceptance_stdout, (
            "Acceptance stdout must contain '*Top Stories*' — "
            "emitted by the 'digest-dry-run' subcommand"
        )

    def test_acceptance_file_references_both_subcommands(self) -> None:
        """The acceptance file must invoke both 'once' and 'digest-dry-run'."""
        text = ACCEPTANCE_FILE.read_text()
        assert " once " in text, (
            "acceptance file must invoke the 'once' subcommand"
        )
        assert "digest-dry-run" in text, (
            "acceptance file must invoke the 'digest-dry-run' subcommand"
        )


