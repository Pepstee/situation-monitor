"""Independent final regression gate — the last line of defence.

Acceptance criteria under test (each assertion can fail on a real regression):

  1. ``pytest tests/`` exits 0 — the full suite passes when run as a fresh subprocess.
  2. Acceptance script exits 0 **and** the dual-lens column text is present in stdout:
       ``#### LEFT``  and  ``#### RIGHT``  (the "lens text") must appear.
  3. ``verdict_brief.txt`` as committed/generated on disk contains exactly:
       line 1: ``DUAL_LENS: Y``
       line 2: ``SPIN_PCT: Y``
       line 3: ``MARKET: Y``

Design note: to prevent infinite subprocess recursion the meta-pytest run
excludes this file plus every other file that also spawns a pytest subprocess.
Every assertion here is capable of failing on a genuine code regression — no
trivially-true checks.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).parent.parent
ACCEPTANCE_FILE = PROJECT_ROOT / "acceptance"
VERDICT_FILE = PROJECT_ROOT / "verdict_brief.txt"

THIS_FILE = Path(__file__).name

# All test files known to spawn a pytest subprocess — exclude all to break cycles.
# Including test_acceptance_regression_guard.py which also spawns pytest via its
# pytest_x_result fixture; omitting it would create a 3-level subprocess chain.
_PYTEST_META_FILES = [
    THIS_FILE,
    "test_regression_guard.py",
    "test_pytest_acceptance_regression.py",
    "test_independent_subprocess_guard.py",
    "test_final_regression_guard.py",
    "test_acceptance_regression_guard.py",
]


